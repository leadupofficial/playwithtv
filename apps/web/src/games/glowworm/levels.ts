/**
 * Glowworm Grove levels. Draw a garden in text, 24 × 14:
 *   #  hedge (crash)     L  dark lantern (pass over it to light it)     S  Glo's head, starting to the right
 *   a / b  burrows: go in one, come out of the other with the same letter     .  grass
 * A garden with no hedge border wraps around the edges. levels.test.ts checks every garden.
 */
export interface WormLevel {
  name: string;
  world: number;
  map: string[];
  /** Fireflies to eat. */
  goal: number;
  /** Milliseconds per step at the start (it speeds up a little with every firefly). */
  stepMs: number;
  /** Seconds for the third star. */
  par: number;
}

